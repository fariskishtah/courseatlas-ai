"""Generate docs/DATA_SOURCE_AUDIT.md from the real registry + vector store (no hand-typed numbers)."""
from __future__ import annotations

import json
import statistics
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from src.vectorstore.indexing import KnowledgeBase  # noqa: E402


def main() -> None:
    kb = KnowledgeBase()
    docs = kb.store.list_docs()
    chunks = kb.store.get_all()
    sizes = [len(c["text"]) for c in chunks]
    sha = Counter(d["sha256"] for d in docs)
    L = ["# Data Source Audit", "", "_Generated by `scripts/audit_sources.py` from the live registry and vector index. Do not edit by hand._", "",
         "All course files are **original educational material written for this project** (`scripts/course_content.py`), released under **CC BY 4.0**. "
         "They are *not* official university course materials. CSV numbers are computed programmatically, not typed.", "",
         "## Totals", ""]
    ok = [d for d in docs if d["status"] == "indexed"]
    L += [f"- Courses: **{len(kb.courses)}**", f"- Documents indexed: **{len(ok)}** / {len(docs)} registered",
          f"- Extraction failures: **{len(docs) - len(ok)}**", f"- Duplicate documents (identical SHA-256): **{sum(1 for v in sha.values() if v > 1)}**",
          f"- PDF pages: **{sum(d['pages'] or 0 for d in ok)}**", f"- Words extracted: **{sum(d['words'] or 0 for d in ok):,}**",
          f"- Characters extracted: **{sum(d['chars'] or 0 for d in ok):,}**", f"- Chunks: **{len(chunks)}** (mean {statistics.mean(sizes):.0f} chars, median {statistics.median(sizes):.0f}, min {min(sizes)}, max {max(sizes)})",
          f"- Embeddings stored: **{kb.store.count()}**", f"- Chunk config: {kb.chunk_size} chars / {kb.chunk_overlap} overlap", ""]
    L += ["## Per course", "", "| Course | Documents | Pages | Words | Chunks | Formats |", "|---|---|---|---|---|---|"]
    for cid, meta in kb.courses.items():
        cd = [d for d in ok if d["course_id"] == cid]
        L.append(f"| {meta['name']} | {len(cd)} | {sum(d['pages'] or 0 for d in cd)} | {sum(d['words'] or 0 for d in cd):,} | {sum(d['n_chunks'] for d in cd)} | {', '.join(sorted({d['file_type'].upper() for d in cd}))} |")
    L += ["", "## Document inventory", "",
          "| Doc ID | Course | Filename | Type | Source | License | Bytes | SHA-256 (first 12) | Pages | Words | Chars | Extraction method | Ingestion | Indexing | Errors |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for d in docs:
        L.append(f"| {d['doc_id']} | {d['course_id']} | {d['filename']} | {d['file_type']} | {(d['source'] or '')[:40]} | {d['license']} | {d['bytes']:,} | {d['sha256'][:12]} | "
                 f"{d['pages'] or '-'} | {d['words'] or 0} | {d['chars'] or 0} | {d['extraction_method']} | {d['status']} | {'indexed' if d['status'] == 'indexed' else 'not indexed'} ({d['n_chunks']} chunks) | {d['error'] or ''} |")
    L += ["", "## Ingestion timing (this machine, warm)", "", "| File type | docs | mean extract s | mean embed s | mean index s |", "|---|---|---|---|---|"]
    for t in sorted({d["file_type"] for d in ok}):
        td = [d for d in ok if d["file_type"] == t]
        m = lambda k: statistics.mean(d[k] or 0 for d in td)  # noqa: E731
        L.append(f"| {t.upper()} | {len(td)} | {m('extract_s'):.4f} | {m('embed_s'):.3f} | {m('index_s'):.4f} |")
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "DATA_SOURCE_AUDIT.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    (ROOT / "artifacts" / "metrics" / "kb_stats.json").write_text(json.dumps(
        {"documents": len(ok), "chunks": len(chunks), "mean_chunk_chars": statistics.mean(sizes), "embeddings": kb.store.count(),
         "words": sum(d["words"] or 0 for d in ok), "pages": sum(d["pages"] or 0 for d in ok), "chunk_sizes": sizes}, indent=2))
    print("wrote docs/DATA_SOURCE_AUDIT.md")


if __name__ == "__main__":
    main()
